import streamlit as st
import pandas as pd
import matplotlib.pyplot as plt
from utils.common import load_metric_file
st.title("🏆 Results & Conclusions")
st.caption("All charts are generated from experiment CSV files only. No synthetic benchmarks are inserted.")
st.subheader("32-way validation comparison")
val=load_metric_file("validation_results.csv",["feature_selection","loss_function","n_features","MAE","RMSE","R2"])
if val is not None:
    st.dataframe(val.sort_values("RMSE"),use_container_width=True,hide_index=True)
    pivot=val.pivot_table(index="feature_selection",columns="loss_function",values="RMSE",aggfunc="mean")
    fig,ax=plt.subplots(figsize=(9,4))
    im=ax.imshow(pivot.to_numpy(),aspect="auto")
    ax.set_xticks(range(len(pivot.columns)),pivot.columns,rotation=35,ha="right")
    ax.set_yticks(range(len(pivot.index)),pivot.index)
    ax.set_title("Validation RMSE heatmap (lower is better)")
    fig.colorbar(im,ax=ax,label="RMSE (Wh)")
    st.pyplot(fig); plt.close(fig)
    top=val.nsmallest(10,"RMSE").copy()
    top["Combination"]=top["feature_selection"].astype(str)+" × "+top["loss_function"].astype(str)
    st.subheader("Top 10 by validation RMSE")
    st.bar_chart(top.set_index("Combination")["RMSE"])
    st.write("Best validation combination:", f"**{top.iloc[0]['Combination']}**")
st.subheader("Held-out test performance")
test=load_metric_file("test_results.csv",["feature_selection","loss_function","MAE","RMSE","R2","interval_coverage","mean_interval_width"])
if test is not None: st.dataframe(test,use_container_width=True,hide_index=True)
st.subheader("Actual vs. predicted and 95% prediction interval")
pred=load_metric_file("test_predictions.csv",["date","actual","predicted","lower_95PI","upper_95PI"])
if pred is not None:
    num=min(200,len(pred)); sample=pred.head(num)
    x=range(num)
    fig,ax=plt.subplots(figsize=(11,4))
    ax.plot(x,sample["actual"],label="Actual",color="black",linewidth=1)
    ax.plot(x,sample["predicted"],label="Predicted",linewidth=1)
    ax.fill_between(list(x),sample["lower_95PI"].to_numpy(),sample["upper_95PI"].to_numpy(),alpha=0.2,label="95% prediction interval")
    ax.set(xlabel="Chronological test observation",ylabel="Energy consumption (Wh)")
    ax.legend(); st.pyplot(fig); plt.close(fig)
    coverage=((pred.actual>=pred.lower_95PI)&(pred.actual<=pred.upper_95PI)).mean()
    st.metric("Observed 95% interval coverage",f"{coverage:.1%}")
st.caption("Use validation metrics to select the configuration; evaluate only the final choice on the test set. Time dependence can affect the nominal interval coverage guarantee.")
